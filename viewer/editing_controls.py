def create_quality_control(qt, parent=None):
    widgets = qt.QtWidgets

    class DensitySpinBox(widgets.QDoubleSpinBox):

        def textFromValue(self, value):
            return format(value, '.15g')

        def valueFromText(self, text):
            return float(text.removesuffix(self.suffix()).strip().replace(',', '.'))

        def validate(self, text, position):
            value = text.removesuffix(self.suffix()).strip().replace(',', '.')
            state = qt.QtGui.QValidator.State
            if value == self.specialValueText():
                return (state.Acceptable, text, position)
            try:
                number = float(value)
            except ValueError:
                partial = not value or value in {'+', '.', '+.'} or value.endswith(('e', 'e+', 'e-'))
                return (state.Intermediate if partial else state.Invalid, text, position)
            valid = math.isfinite(number) and self.minimum() <= number <= self.maximum()
            return (state.Acceptable if valid else state.Invalid, text, position)
    frame = widgets.QWidget(parent)
    frame.setObjectName('PlacementQualityControl')
    row = widgets.QHBoxLayout(frame)
    row.setContentsMargins(0, 0, 0, 0)
    row.setSpacing(5)
    row.addWidget(widgets.QLabel('Ayrinti'))
    density = DensitySpinBox()
    density.setObjectName('PlacementCcaControl')
    density.setAccessibleName('Yerlesim ayrintisi CCA')
    density.setRange(0, 10000)
    density.setDecimals(323)
    density.setSingleStep(5)
    density.setSpecialValueText('Otomatik')
    density.setSuffix(' CCA/m')
    density.setKeyboardTracking(False)
    density.setFixedWidth(145)
    density.setToolTip('1 metre icindeki nominal ornek sikligi. 250 CCA/m = 4 mm hucre araligi. Olcum hassasiyeti degildir; kaynaktan yeni ayrinti uretmez. 0: otomatik hafif gorunum. Degisiklik Uygula ile secili taramalara uygulanir.')
    row.addWidget(density)
    apply = widgets.QPushButton('Uygula')
    apply.setObjectName('ApplyPlacementCcaButton')
    apply.setToolTip('Secili tarama veya grubun yerlesim gorunumunu bu ayrintida hazirla.')
    row.addWidget(apply)
    return frame

def create_evidence_combo(qt, parent=None):
    from viewer.evidence_labels import EVIDENCE_ITEMS

    class EvidenceCombo(qt.QtWidgets.QComboBox):

        def setCurrentText(self, text):
            index = self.findData(text)
            if index >= 0:
                self.setCurrentIndex(index)
            else:
                super().setCurrentText(text)
    combo = EvidenceCombo(parent)
    for key, label, description in EVIDENCE_ITEMS:
        combo.addItem(label, key)
        combo.setItemData(combo.count() - 1, description, qt.QtCore.Qt.ItemDataRole.ToolTipRole)
    return combo
